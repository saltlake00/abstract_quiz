# -*- coding: utf-8 -*-
"""Turn locally supplied images into synchronized triangle and brush quiz questions."""

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "data" / "extra_questions.js"


def load_module(name, filename):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / filename)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def seed_for(question_id):
    return int.from_bytes(hashlib.sha256(question_id.encode("utf-8")).digest()[:4], "big")


def checked_text(value, field):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field} must be a non-empty string")
    return value.strip()


def build(manifest_path):
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    specs = payload.get("questions") if isinstance(payload, dict) else None
    if not isinstance(specs, list) or not specs:
        raise ValueError("manifest must contain a non-empty questions array")

    base_data = (ROOT / "data" / "questions.js").read_text(encoding="utf-8")
    base_questions = json.loads(base_data.split("=", 1)[1].strip().rstrip(";"))
    seen = {q["id"] for q in base_questions}
    triangles = load_module("quiz_triangles", "01_build_quiz_dataset.py")
    painter = load_module("quiz_painter", "03_build_painter_dataset.py")
    questions, paintings = [], {}

    for spec in specs:
        if not isinstance(spec, dict):
            raise ValueError("each question must be an object")
        question_id = checked_text(spec.get("id"), "id")
        if not question_id.replace("_", "").isalnum() or question_id in seen:
            raise ValueError(f"invalid or duplicate id: {question_id}")
        seen.add(question_id)
        category = checked_text(spec.get("category"), "category")
        if category == "전체":
            raise ValueError("'전체' is reserved for the combined category")
        title = checked_text(spec.get("title"), "title")
        answers = spec.get("answers")
        if not isinstance(answers, list) or not answers:
            raise ValueError(f"{question_id}: answers must be a non-empty array")
        answers = [checked_text(value, "answer") for value in answers]
        image_path = (manifest_path.parent / checked_text(spec.get("image"), "image")).resolve()
        if not image_path.is_file():
            raise FileNotFoundError(image_path)
        focus = spec.get("focus", [0.5, 0.5])
        if not isinstance(focus, list) or len(focus) != 2 or any(not isinstance(v, (float, int)) or not 0 <= v <= 1 for v in focus):
            raise ValueError(f"{question_id}: focus must be [x, y] with values from 0 to 1")

        with Image.open(image_path) as source:
            image = ImageOps.fit(
                source.convert("RGB"), (180, 220),
                method=Image.Resampling.LANCZOS, centering=tuple(focus),
            )
        seed = seed_for(question_id)
        triangle_data = triangles.decompose_image_to_triangles(image, num_shapes=260, seed=seed)
        questions.append({
            "id": question_id,
            "category": category,
            "title": title,
            "answers": answers,
            "hint1": checked_text(spec.get("hint1"), "hint1"),
            "hint2": checked_text(spec.get("hint2"), "hint2"),
            "desc": str(spec.get("desc", "")).strip(),
            "width": triangle_data["width"],
            "height": triangle_data["height"],
            "bg": triangle_data["bg"],
            "scale": 1,
            "polygons": triangle_data["polygons"],
        })
        paintings[question_id] = painter.make_strokes(image, seed)
        print(f"{question_id}: {len(triangle_data['polygons'])} triangles, {len(paintings[question_id]['strokes'])} brush strokes")
    return questions, paintings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path, help="JSON file with question metadata and local image paths")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    questions, paintings = build(args.manifest.resolve())
    args.output.write_text(
        "// Generated by scripts/04_add_image_questions.py.\n"
        + "window.QUIZ_EXTRA_QUESTIONS = "
        + json.dumps(questions, ensure_ascii=False, separators=(",", ":"))
        + ";\nwindow.QUIZ_EXTRA_PAINTINGS = "
        + json.dumps(paintings, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
